import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
const source = await readFile(new URL('../src/targets/Printer3D/Marlin/printJob.js', import.meta.url), 'utf8')
const { readPrintJob, sdPrintCommand } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'))
const reply = (data, status = 'ok') => JSON.stringify({ cmd: '701', status, data })
assert.equal(sdPrintCommand('/', 'motion.gco'), '[ESP700]/SD/motion.gco')
assert.equal(sdPrintCommand('/jobs/', 'calibration cube.gcode'), '[ESP700]/SD/jobs/calibration cube.gcode')
assert.throws(() => sdPrintCommand('/', 'a.gco\nM112'))
assert.throws(() => sdPrintCommand('/', 'a;M112.gco'))
const running = readPrintJob(reply({status:'processing', total:'1000', processed:'250', name:'/motion.gco'}))
assert.equal(running.progress, 25)
assert.equal(running.active, true)
for (const state of ['pause', 'pausing', 'cancelling']) {
    const next = readPrintJob(reply(state), running)
    assert.equal(next.name, '/motion.gco')
    assert.equal(next.progress, 25)
    assert.equal(next.active, true)
}
const fault = readPrintJob(reply({status:'no stream', code:'1'}, 'error'), running)
assert.equal(fault.error, true)
assert.equal(fault.state, 'error')
assert.equal(readPrintJob(reply({status:'no stream', code:'12'})).error, true)
const idle = readPrintJob(reply('no stream'), running)
assert.equal(idle.active, false)
assert.equal(idle.name, '')
assert.throws(() => readPrintJob('broken JSON'))
assert.throws(() => readPrintJob(JSON.stringify({cmd:'800', data:'no stream'})))
assert.throws(() => readPrintJob(reply('Pause requested')))
console.log('Print workflow checks passed: paths, control states, progress, faults, malformed replies.')
